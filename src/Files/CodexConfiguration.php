<?php

declare(strict_types=1);

namespace MrKoopie\LaravelAiHarness\Files;

use MrKoopie\LaravelAiHarness\Config\Config;
use MrKoopie\LaravelAiHarness\Config\ConfigLoader;
use MrKoopie\LaravelAiHarness\Support\GlobalInstallation;

/** Generate Codex's setup and subprocess configuration from one selection. */
final readonly class CodexConfiguration
{
    public const MARKER = '# Generated by ai-harness init --agent=codex';

    public function __construct(private SafeWriter $writer = new SafeWriter) {}

    /** Preserve explicitly configured environments during ordinary init/update refreshes. */
    public static function configured(string $root, string $path): bool
    {
        if (is_link($root.'/'.$path)) {
            throw new FileException("Refusing to read symbolic link [{$path}].");
        }

        return is_file($root.'/'.$path) && str_starts_with((string) file_get_contents($root.'/'.$path), self::MARKER."\n");
    }

    /** @return array<string, string> */
    public function variables(Config $config): array
    {
        return $config->environment();
    }

    /**
     * Plan a conservative edit of the explicit shell table; never rewrite unrelated TOML.
     *
     * @param  array<string, string>  $variables
     */
    public function shellConfig(string $root, array $variables): string
    {
        $path = '.codex/config.toml';
        $this->writer->assertSafePath($root, $path);
        if (is_link($root.'/'.$path)) {
            throw new FileException('Refusing to edit a symbolic link at .codex/config.toml.');
        }
        $existing = is_file($root.'/'.$path) ? file_get_contents($root.'/'.$path) : '';
        if ($existing === false || strlen($existing) > 262144) {
            throw new FileException('Unable to read .codex/config.toml or file exceeds 256 KiB.');
        }
        // Multiline strings can contain apparent table headers. Refuse ambiguous edits.
        if (str_contains($existing, '"""') || str_contains($existing, "'''")) {
            throw new FileException('Codex config contains multiline strings; move them to another config layer before generating shell settings.');
        }
        $lines = explode("\n", rtrim($existing, "\n"));
        $table = false;
        $found = false;
        $section = '';
        $result = [];
        foreach ($lines as $line) {
            if (preg_match('/^\s*\[.*\]/', $line) === 1) {
                if ($table) {
                    $result = [...$result, ...$this->assignments($variables)];
                }
                $section = trim(explode(']', ltrim(trim($line), '['), 2)[0]);
                if (str_contains($section, '\\')) {
                    throw new FileException('Escaped TOML table headers cannot be merged safely; use explicit unescaped table names.');
                }
                $section = trim($section, "\"'");
                $table = preg_match('/^\s*\[shell_environment_policy\.set\]\s*(?:#.*)?$/', $line) === 1;
                if ($table && $found) {
                    throw new FileException('Duplicate shell_environment_policy.set table in .codex/config.toml.');
                }
                $found = $found || $table;
                if (! $table && preg_match('/^\s*\[.*shell_environment_policy.*set/', $line) === 1) {
                    throw new FileException('Use an explicit [shell_environment_policy.set] table before generating Codex settings.');
                }
            } elseif (($section === '' && preg_match('/^\s*["\']?shell_environment_policy["\']?\s*[.=]/', $line) === 1)
                || ($section === 'shell_environment_policy' && preg_match('/^\s*["\']?set["\']?\s*[.=]/', $line) === 1)) {
                throw new FileException('Inline or dotted shell environment settings cannot be merged; use [shell_environment_policy.set].');
            }
            if ($table && preg_match('/^\s*["\']?(AI_HARNESS_[A-Z_]+)["\']?\s*([=.])/', $line, $match) === 1 && in_array($match[1], ConfigLoader::environmentNames(), true)) {
                if ($match[2] !== '=') {
                    throw new FileException('Harness shell settings must be scalar TOML strings.');
                }
                if (preg_match('/=\s*(?:"(?:[^"\\\\]|\\\\.)*"|\x27[^\x27]*\x27)\s*(?:#.*)?$/', $line) !== 1) {
                    throw new FileException('Harness shell settings must be single-line TOML strings.');
                }

                continue;
            }
            $result[] = $line;
        }
        if (! $found && $variables !== []) {
            $result[] = '[shell_environment_policy.set]';
        }
        if ($table || ! $found) {
            $result = [...$result, ...$this->assignments($variables)];
        }

        return ltrim(implode("\n", $result), "\n")."\n";
    }

    /**
     * @param  array<string, string>  $variables
     * @return list<string>
     */
    private function assignments(array $variables): array
    {
        $lines = [];
        foreach ($variables as $name => $value) {
            $lines[] = $name.' = '.json_encode($value, JSON_THROW_ON_ERROR | JSON_UNESCAPED_SLASHES);
        }

        return $lines;
    }

    public function write(string $root, Config $config, bool $global, bool $migrate, bool $build, string $shellConfig): void
    {
        $variables = $this->variables($config);
        $command = $global ? 'ai-harness' : './.ai-harness';
        $exports = '';
        foreach ($variables as $key => $value) {
            $exports .= 'export '.$key.'='.escapeshellarg($value)."\n";
        }
        $init = $command.' init'.($global ? ' --global' : '').' --agents='.escapeshellarg(implode(',', $config->agents))
            .($migrate ? ' --migrate' : '').($build ? ' --build' : '');
        $setup = $command.' setup'.($migrate ? ' --migrate' : '').($build ? ' --build' : '');
        // Login shells resolve Composer's global bin on machines where the app lacks it in PATH.
        $setupScript = 'bash -lc '.escapeshellarg("set -e\n".$exports.$init."\n".$setup);
        $cleanupScript = 'bash -lc '.escapeshellarg("set -e\n".$exports.$command.' cleanup && '.$command.' down');
        $environment = self::MARKER."\nversion = 1\nname = \"Laravel AI Harness (Codex)\"\n\n[setup]\nscript = \"\"\"\n"
            .$this->tomlMultiline($setupScript)."\n\"\"\"\n\n[cleanup]\nscript = \"\"\"\n".$this->tomlMultiline($cleanupScript)."\n\"\"\"\n";
        $this->writer->write($root, '.codex/config.toml', $shellConfig);
        if ($config->worktrees) {
            $this->writer->write($root, $global ? GlobalInstallation::CODEX_ENVIRONMENT : '.codex/environments/environment.toml', $environment);
        } else {
            $path = $global ? GlobalInstallation::CODEX_ENVIRONMENT : '.codex/environments/environment.toml';
            if (self::configured($root, $path)) {
                $this->writer->removeOwnedFile($root, $path, (string) file_get_contents($root.'/'.$path));
            }
        }
    }

    /** Remove generated Codex integration while preserving unrelated user settings. */
    public function disable(string $root, bool $global, string $shellConfig): void
    {
        if (is_file($root.'/.codex/config.toml')) {
            $this->writer->write($root, '.codex/config.toml', $shellConfig);
        }
        $path = $global ? GlobalInstallation::CODEX_ENVIRONMENT : '.codex/environments/environment.toml';
        if (self::configured($root, $path)) {
            $this->writer->removeOwnedFile($root, $path, (string) file_get_contents($root.'/'.$path));
        }
    }

    private function tomlMultiline(string $script): string
    {
        return str_replace(['\\', '"'], ['\\\\', '\\"'], $script);
    }
}
